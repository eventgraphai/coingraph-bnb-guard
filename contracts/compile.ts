// Compiles the contracts in this folder with solc-js and writes artifacts.generated.ts (ABI, creation and runtime bytecode).
// Run: pnpm tsx contracts/compile.ts
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const solc = require("solc");
const dir = new URL(".", import.meta.url);
const files = ["CoinGraphGuard.sol", "ProofLog.sol", "CoinGraphGuardAtlas.sol"];
// The vendored Atlas SDK imports "base/...", "libraries/...", "constants/...", "interfaces/..." (its src folder).
const findImports = (path: string) => {
  const p = /^(base|libraries|constants|interfaces)\//.test(path) ? `vendor/atlas/${path}` : path;
  try {
    return { contents: readFileSync(new URL(p, dir), "utf8") };
  } catch {
    return { error: `not found: ${path}` };
  }
};

const out = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: "Solidity",
      sources: Object.fromEntries(files.map((f) => [f, { content: readFileSync(new URL(f, dir), "utf8") }])),
      settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: "paris", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } } },
    }),
    { import: findImports },
  ),
);
const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e: { formattedMessage: string }) => e.formattedMessage).join("\n"));
  process.exit(1);
}
let ts = "// Generated by contracts/compile.ts. Do not edit.\n";
for (const f of files) {
  const name = f.replace(".sol", "");
  const c = out.contracts[f][name];
  ts += `export const ${name} = { abi: ${JSON.stringify(c.abi)}, bytecode: "0x${c.evm.bytecode.object}", runtime: "0x${c.evm.deployedBytecode.object}" } as const;\n`;
  console.log(`${name}: ${c.evm.deployedBytecode.object.length / 2} bytes`);
}
writeFileSync(new URL("artifacts.generated.ts", dir), ts);
