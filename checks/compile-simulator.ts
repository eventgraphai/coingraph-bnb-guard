// Compiles Simulator.sol with solc-js and writes simulator.generated.ts (runtime bytecode + ABI).
// Run: pnpm tsx checks/compile-simulator.ts
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const solc = require("solc");
const dir = new URL(".", import.meta.url);
const source = readFileSync(new URL("Simulator.sol", dir), "utf8");

const out = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: "Solidity",
      sources: { "Simulator.sol": { content: source } },
      settings: { optimizer: { enabled: true, runs: 200 }, viaIR: true, outputSelection: { "*": { "*": ["abi", "evm.deployedBytecode.object"] } } },
    }),
  ),
);
const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e: { formattedMessage: string }) => e.formattedMessage).join("\n"));
  process.exit(1);
}
const c = out.contracts["Simulator.sol"].Simulator;
writeFileSync(
  new URL("simulator.generated.ts", dir),
  `// Generated by compile-simulator.ts from Simulator.sol. Do not edit.\nexport const simulatorAbi = ${JSON.stringify(c.abi)} as const;\nexport const simulatorCode = "0x${c.evm.deployedBytecode.object}" as const;\n`,
);
console.log(`Simulator compiled: ${c.evm.deployedBytecode.object.length / 2} bytes`);
